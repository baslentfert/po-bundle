//! # po-bundle
//!
//! Gettext `.po` translations, baked into your binary, for strings in Rust
//! code and in Slint UIs alike.
//!
//! - **One file per language**, in the layout Slint's bundled translations
//!   already use: `translations/<lang>/LC_MESSAGES/<crate>.po`. Translators
//!   use the tools they know (Poedit, Lokalize, Weblate, …).
//! - **English source strings** in the code, like gettext and Slint's
//!   `@tr()`: `tr!("Share this screen")`. Missing translations fall back
//!   to the source text, so nothing ever shows up empty.
//! - **Named placeholders**: `tr!("Seen as “{name}”", name = host)`.
//! - **Context** for identical source strings that mean different things,
//!   with the same syntax as Slint: `tr!("menu" => "Open")`.
//! - **The OS language by default**, or the user's choice
//!   ([`set_language`]); a callback when it changes ([`on_change`]).
//! - **Nothing to load at run time**: `build.rs` turns the `.po` files into
//!   static tables ([`build::compile`]).
//! - **`po-bundle update`** collects the strings from your `.rs` (and, via
//!   `slint-tr-extractor`, `.slint`) files and updates every `.po` file:
//!   new strings are added, removed ones become obsolete (`#~`).
//!
//! ```ignore
//! // build.rs
//! fn main() {
//!     po_bundle::build::compile("translations");
//! }
//!
//! // main.rs
//! po_bundle::include_translations!();
//! use po_bundle::tr;
//!
//! fn main() {
//!     po_bundle::set_language(None); // follow the OS
//!     println!("{}", tr!("Hello, {name}!", name = "Bas"));
//! }
//! ```

use std::borrow::Cow;
use std::sync::RwLock;

pub mod build;
pub mod po;
pub mod slint_widgets;

/// The translations of one crate, generated by [`build::compile`] and
/// included with [`include_translations!`].
pub struct Catalog {
    /// The gettext domain: the crate name.
    pub domain: &'static str,
    /// Per language code, the messages sorted by (context, id).
    pub languages: &'static [(&'static str, &'static [Message])],
}

/// One translated message.
pub struct Message {
    /// Empty when there is no context.
    pub context: &'static str,
    pub id: &'static str,
    pub text: &'static str,
}

impl Catalog {
    /// The translation of `id` in the current language, or `id` itself.
    pub fn get(&self, context: &str, id: &'static str) -> &'static str {
        let taal = LANGUAGE.read().unwrap();
        self.lookup(&taal).and_then(|messages| {
            messages
                .binary_search_by(|m| (m.context, m.id).cmp(&(context, id)))
                .ok()
                .map(|i| messages[i].text)
        })
        .unwrap_or(id)
    }

    /// The messages for `code`: exact (`pt_BR`), else the base language
    /// (`pt`).
    fn lookup(&self, code: &str) -> Option<&'static [Message]> {
        let find = |c: &str| self.languages.iter().find(|(l, _)| same_language(l, c)).map(|(_, m)| *m);
        find(code).or_else(|| find(base(code)))
    }

    /// The language codes this crate has translations for, plus the source
    /// language (English).
    pub fn language_codes(&self) -> Vec<&'static str> {
        let mut codes: Vec<&'static str> = std::iter::once("en").chain(self.languages.iter().map(|(l, _)| *l)).collect();
        codes.sort_unstable();
        codes.dedup();
        codes
    }
}

fn base(code: &str) -> &str {
    code.split(['-', '_', '.', '@']).next().unwrap_or(code)
}

fn same_language(a: &str, b: &str) -> bool {
    a.replace('-', "_").eq_ignore_ascii_case(&b.replace('-', "_"))
}

/// The current language code (`"nl"`, `"pt_BR"`); starts as the OS
/// language.
static LANGUAGE: RwLock<String> = RwLock::new(String::new());
/// What the user chose; `None` follows the OS.
static CHOICE: RwLock<Option<String>> = RwLock::new(None);
type Listener = Box<dyn Fn(&str) + Send + Sync>;
static LISTENERS: RwLock<Vec<Listener>> = RwLock::new(Vec::new());

/// The language of the operating system, as a code (`"nl"`, `"de_AT"`).
pub fn os_language() -> String {
    sys_locale::get_locale().unwrap_or_else(|| "en".to_string()).replace('-', "_")
}

/// Chooses the language: `Some("nl")`, or `None` to follow the OS.
/// Calls the [`on_change`] callbacks when the language really changes.
///
/// With the `slint` feature this also switches Slint's bundled
/// translations; Slint wants that after the first component exists.
pub fn set_language(choice: Option<&str>) {
    *CHOICE.write().unwrap() = choice.map(String::from);
    let code = choice.map_or_else(os_language, String::from);
    let changed = {
        let mut l = LANGUAGE.write().unwrap();
        let changed = *l != code;
        *l = code.clone();
        changed
    };
    #[cfg(feature = "slint")]
    {
        // Slint knows the base language folder; "" is its source language.
        let slint_code = if base(&code) == "en" { "" } else { &code };
        if slint::select_bundled_translation(slint_code).is_err() {
            let _ = slint::select_bundled_translation(base(&code));
        }
    }
    if changed {
        for f in LISTENERS.read().unwrap().iter() {
            f(&code);
        }
    }
}

/// The language now in use.
pub fn language() -> String {
    let l = LANGUAGE.read().unwrap();
    if l.is_empty() { os_language() } else { l.clone() }
}

/// What the user chose with [`set_language`]; `None` = follow the OS.
pub fn chosen() -> Option<String> {
    CHOICE.read().unwrap().clone()
}

/// Called with the new language code whenever it changes, e.g. to set the
/// texts of a window again.
pub fn on_change(f: impl Fn(&str) + Send + Sync + 'static) {
    LISTENERS.write().unwrap().push(Box::new(f));
}

/// The name of a language in that language ("Nederlands", "Deutsch"), for
/// a language menu; the code itself when unknown.
pub fn native_name(code: &str) -> &str {
    match base(code) {
        "ar" => "العربية",
        "cs" => "Čeština",
        "da" => "Dansk",
        "de" => "Deutsch",
        "el" => "Ελληνικά",
        "en" => "English",
        "es" => "Español",
        "fi" => "Suomi",
        "fr" => "Français",
        "fy" => "Frysk",
        "he" => "עברית",
        "hu" => "Magyar",
        "it" => "Italiano",
        "ja" => "日本語",
        "ko" => "한국어",
        "nb" | "no" => "Norsk bokmål",
        "nl" => "Nederlands",
        "pl" => "Polski",
        "pt" => "Português",
        "ro" => "Română",
        "ru" => "Русский",
        "sv" => "Svenska",
        "tr" => "Türkçe",
        "uk" => "Українська",
        "zh" => "中文",
        _ => code,
    }
}

/// Fills `{name}` placeholders; unknown ones stay as they are. `{{` and
/// `}}` give literal braces.
pub fn fill<'a>(text: &'a str, values: &[(&str, &dyn std::fmt::Display)]) -> Cow<'a, str> {
    if !text.contains('{') && !text.contains('}') {
        return Cow::Borrowed(text);
    }
    let mut out = String::with_capacity(text.len() + 16);
    let mut rest = text;
    while let Some(i) = rest.find(['{', '}']) {
        out.push_str(&rest[..i]);
        let tail = &rest[i..];
        if tail.starts_with("{{") || tail.starts_with("}}") {
            out.push(tail.as_bytes()[0] as char);
            rest = &tail[2..];
            continue;
        }
        if let Some(end) = tail.find('}').filter(|_| tail.starts_with('{')) {
            let name = &tail[1..end];
            match values.iter().find(|(n, _)| *n == name) {
                Some((_, v)) => {
                    use std::fmt::Write;
                    let _ = write!(out, "{v}");
                }
                None => out.push_str(&tail[..=end]),
            }
            rest = &tail[end + 1..];
        } else {
            out.push(tail.as_bytes()[0] as char);
            rest = &tail[1..];
        }
    }
    out.push_str(rest);
    Cow::Owned(out)
}

/// Includes the tables that [`build::compile`] generated for this crate.
/// Put it once at the crate root; [`tr!`] uses it.
#[macro_export]
macro_rules! include_translations {
    () => {
        #[doc(hidden)]
        #[allow(dead_code)]
        pub(crate) static __PO_BUNDLE: $crate::Catalog = include!(concat!(env!("OUT_DIR"), "/po_bundle.rs"));
    };
}

/// Translates a string literal into the current language.
///
/// - `tr!("Open")` → `&'static str`
/// - `tr!("menu" => "Open")` → with a context, like Slint's `@tr`
/// - `tr!("Hello, {name}!", name = n)` → `Cow<str>` with the placeholder
///   filled in
///
/// The table is the calling crate's own (`crate::`), from
/// [`include_translations!`].
#[macro_export]
#[allow(clippy::crate_in_macro_def)]
macro_rules! tr {
    ($ctx:literal => $id:literal) => {
        crate::__PO_BUNDLE.get($ctx, $id)
    };
    ($id:literal) => {
        crate::__PO_BUNDLE.get("", $id)
    };
    ($ctx:literal => $id:literal, $($name:ident = $value:expr),+ $(,)?) => {
        $crate::fill(crate::__PO_BUNDLE.get($ctx, $id), &[$((stringify!($name), &$value as &dyn ::std::fmt::Display)),+])
    };
    ($id:literal, $($name:ident = $value:expr),+ $(,)?) => {
        $crate::fill(crate::__PO_BUNDLE.get("", $id), &[$((stringify!($name), &$value as &dyn ::std::fmt::Display)),+])
    };
}

/// The languages this crate can show, for a language menu: (code, native
/// name), sorted by code.
#[macro_export]
#[allow(clippy::crate_in_macro_def)]
macro_rules! languages {
    () => {
        crate::__PO_BUNDLE.language_codes().into_iter().map(|c| (c, $crate::native_name(c))).collect::<Vec<_>>()
    };
}

#[cfg(test)]
mod tests {
    use super::*;

    static TEST: Catalog = Catalog {
        domain: "test",
        languages: &[
            ("de", &[Message { context: "", id: "Open", text: "Öffnen" }]),
            (
                "nl",
                &[
                    Message { context: "", id: "Hello, {name}!", text: "Hallo, {name}!" },
                    Message { context: "", id: "Open", text: "Openen" },
                    Message { context: "door", id: "Open", text: "Open" },
                ],
            ),
        ],
    };

    #[test]
    fn looks_up_with_fallback_and_context() {
        set_language(Some("nl_BE"));
        assert_eq!(TEST.get("", "Open"), "Openen");
        assert_eq!(TEST.get("door", "Open"), "Open");
        assert_eq!(TEST.get("", "Close"), "Close");
        assert_eq!(fill(TEST.get("", "Hello, {name}!"), &[("name", &"Bas")]), "Hallo, Bas!");
        set_language(Some("fr"));
        assert_eq!(TEST.get("", "Open"), "Open");
        set_language(Some("de"));
        assert_eq!(TEST.get("", "Open"), "Öffnen");
        assert_eq!(TEST.language_codes(), ["de", "en", "nl"]);
    }

    #[test]
    fn fills_placeholders() {
        assert_eq!(fill("{a} and {b}", &[("a", &1), ("b", &"two")]), "1 and two");
        assert_eq!(fill("{{literal}} {missing}", &[]), "{literal} {missing}");
        assert!(matches!(fill("plain", &[]), Cow::Borrowed(_)));
    }
}
